/** Regenerate after editing layout.ts, pageSvg.ts, or runtime.ts:
 * node packages/shared/src/menu/generate-runtime.mjs
 * A literal source payload survives Metro, Babel, SWC, and minification without closure references.
 */
import {readFileSync,writeFileSync} from 'node:fs';
import {createRequire} from 'node:module';
const require=createRequire(new URL('../../../../apps/web/package.json',import.meta.url));
const ts=require('typescript');
export function generateMenuRuntimeSource(){
 const files=['design.ts','designLayout.ts','layout.ts','pageSvg.ts','runtime.ts'];
 const body=files.map(file=>readFileSync(new URL(file,import.meta.url),'utf8')
  .replace(/\nexport function layoutMenu\([\s\S]*$/,'')
  .replace(/^import .*;\r?\n/gm,'')
  .replace(/^export /gm,'')).join('\n');
 return ts.transpileModule(`function startMenuRenderer(initial,styles){\n${body}\nmenuRendererRuntime(initial,styles,menuLayoutEngine,menuPageSvg);\n}`,{compilerOptions:{target:ts.ScriptTarget.ES2020,module:ts.ModuleKind.None,removeComments:true}}).outputText;
}
const output='// Generated by generate-runtime.mjs. Do not edit.\nexport const MENU_RUNTIME_SOURCE = '+JSON.stringify(generateMenuRuntimeSource())+';\n';
if(process.argv.includes('--check')){
 if(readFileSync(new URL('runtimeSource.ts',import.meta.url),'utf8')!==output)throw new Error('Menu runtime source is stale; run node packages/shared/src/menu/generate-runtime.mjs');
}else writeFileSync(new URL('runtimeSource.ts',import.meta.url),output);
