_QUANTITY_UNIT_RE = re.compile(
    r"(?:^|\s)(?:lb|lbs|oz|kg|g|gram|grams|ml|l|cup|cups|tbsp|tsp|package|packages)(?:$|\s)",
    re.IGNORECASE,
)
_BRAND_RE = re.compile(
    r"\b(?:bibigo|kikkoman|knorr|lao gan ma|laoganma|lee kum kee)\b",
    re.IGNORECASE,
)
_RECIPE_DESCRIPTOR_RE = re.compile(
    r"\b(?:fresh|freshly|chopped|diced|sliced|minced)\b|新鲜|切块|切片|切碎|剁碎",
    re.IGNORECASE,
)


def _is_valid_query(q: str) -> bool:
    if not q or q != q.strip() or " ".join(q.split()) != q or len(q) > 60:
        return False
    if any(character.isdigit() for character in q):
        return False
    return not any(
        pattern.search(q)
        for pattern in (_QUANTITY_UNIT_RE, _BRAND_RE, _RECIPE_DESCRIPTOR_RE)
    )


def expand_query(q: str) -> list[str]:
    query = q.strip()
    if not query:
        return []
    variations = {query}
    plural = _PLURAL_VARIATIONS.get(query.lower())
    if plural:
        variations.add(plural)
    return sorted(variations)


ALL_QUERIES = sorted(
    {
        variation.strip().casefold()
        for query in COMMON_INGREDIENTS
        for variation in expand_query(query)
        if variation.strip() and _is_valid_query(variation)
    }
)
